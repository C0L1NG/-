"""Generate Web and native theme variables from one reviewed palette."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def declarations(values):
    return "\n".join(f"  --{key}: {value};" for key, value in values.items())


def outputs():
    tokens = json.loads((ROOT / "design/tokens.json").read_text())
    css = "/* Generated by scripts/generate-design-tokens.py. */\n"
    css += (
        ":root {\n" + declarations({**tokens["shared"], **tokens["console"]}) + "\n}\n"
    )
    for theme in ("agent-dark", "agent-light"):
        css += f".{theme} {{\n" + declarations(tokens[theme]) + "\n}\n"
    result = {"web/app/design-tokens.css": css}
    for folder, theme in (
        ("miniprogram", "agent-dark"),
        ("admin_miniprogram", "console"),
    ):
        values = {**tokens["shared"], **tokens[theme]}
        values = {
            key: str(int(value[:-2]) * 2) + "rpx" if value.endswith("px") else value
            for key, value in values.items()
        }
        result[f"{folder}/design-tokens.wxss"] = (
            "/* Generated from design/tokens.json. */\npage {\n"
            + declarations(values)
            + "\n}\n"
        )
        app_path = ROOT / folder / "app.json"
        app = json.loads(app_path.read_text())
        background = values.get("agent-bg", values.get("console-bg"))
        muted = values.get("agent-muted", values.get("console-muted"))
        app["window"].update(
            navigationBarBackgroundColor=background, backgroundColor=background
        )
        app["tabBar"].update(
            color=muted, selectedColor=values["positive"], backgroundColor=background
        )
        result[f"{folder}/app.json"] = (
            json.dumps(app, ensure_ascii=False, indent=2) + "\n"
        )
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for relative, content in outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated design tokens are stale: {relative}")
        else:
            path.write_text(content)
    print(
        "Design tokens match"
        if args.check
        else "Generated Web and native design tokens"
    )
